# -*- coding: utf-8 -*-
"""B 站素材配套服务（kele-study-english 听写导入用）。

在电脑上运行本服务，手机 App（同一局域网）把 B 站视频地址交给本服务：
服务用 yt-dlp 拉取音频（m4a）与字幕（转成 SRT），App 再从本服务取回两份文件，
复用 App 内既有的「字幕解析 → 按句切分 → 落库」管线。

仅供个人学习使用，素材版权归原权利人。

接口：
  GET  /api/ping                    健康检查
  POST /api/bili/import             {url, cookie?} -> {jobId}
  GET  /api/bili/job/<id>           状态/进度/标题
  GET  /api/bili/job/<id>/audio     m4a 音频字节流
  GET  /api/bili/job/<id>/subtitle  SRT 字幕文本
"""

import json
import re
import shutil
import tempfile
import threading
import time
import uuid
from pathlib import Path
from urllib.parse import parse_qs, urlparse

import requests
from flask import Flask, jsonify, request, send_file
from yt_dlp import YoutubeDL

app = Flask(__name__)

SERVICE_VERSION = "0.1.0"
JOB_TTL_SECONDS = 30 * 60  # 完成后文件保留 30 分钟，过期清理

_BILI_HOSTS = ("bilibili.com", "b23.tv")
_UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
)

_jobs = {}
_lock = threading.Lock()


def _job_headers(cookie: str | None) -> dict:
    headers = {"User-Agent": _UA, "Referer": "https://www.bilibili.com/"}
    if cookie:
        headers["Cookie"] = cookie.strip()
    return headers


def _write_cookiefile(cookie: str | None, workdir: Path) -> str | None:
    """把 App 传来的 Cookie 请求头转成 Netscape 格式文件，供 yt-dlp 的 cookiefile 读取。

    新版 yt-dlp 已弃用把 Cookie 放进 http_headers（会告警，且 Cookie 被限定到
    下载 URL 的域）；这里显式声明 .bilibili.com 作用域。文件只写在本次任务的
    临时目录内，随任务结束一并删除。
    """
    if not cookie:
        return None
    raw = cookie.strip()
    if raw.lower().startswith("cookie:"):
        raw = raw[len("cookie:"):].strip()

    pairs: list[tuple[str, str]] = []
    for part in raw.split(";"):
        name, sep, value = part.strip().partition("=")
        name, value = name.strip(), value.strip()
        if not (sep and name and value):
            continue
        if any(c in name + value for c in "\t\r\n"):
            continue
        pairs.append((name, value))
    if not pairs:
        return None

    expires = int(time.time()) + 30 * 24 * 3600
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by bili-helper for this import job only.",
    ]
    for name, value in pairs:
        lines.append(f".bilibili.com\tTRUE\t/\tTRUE\t{expires}\t{name}\t{value}")
    path = workdir / "cookies.txt"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(path)


def _ydl_auth_opts(headers: dict, cookiefile: str | None) -> dict:
    """yt-dlp 的认证参数：Cookie 走 cookiefile，不再放进 http_headers。"""
    opts = {
        "http_headers": {k: v for k, v in headers.items() if k.lower() != "cookie"},
    }
    if cookiefile:
        opts["cookiefile"] = cookiefile
    return opts


def _is_bili_url(url: str) -> bool:
    try:
        host = urlparse(url).hostname or ""
    except ValueError:
        return False
    host = host.lower()
    return any(host == h or host.endswith("." + h) for h in _BILI_HOSTS)


def _resolve_short_link(url: str, headers: dict) -> str:
    """b23.tv 短链先跟随跳转拿到真实地址。"""
    if "b23.tv" not in (urlparse(url).hostname or ""):
        return url
    try:
        resp = requests.get(url, headers=headers, timeout=15, allow_redirects=True)
        if resp.url and _is_bili_url(resp.url):
            return resp.url
    except requests.RequestException:
        pass
    return url


def _pick_part(url: str, info: dict) -> dict:
    """多 P 视频按 URL 里的 p= 参数选分 P，默认第一个。"""
    entry = info
    if "entries" in info:
        entries = [e for e in (info.get("entries") or []) if e]
        if not entries:
            raise RuntimeError("该视频没有可用的分 P。")
        try:
            p = int((parse_qs(urlparse(url).query).get("p") or ["1"])[0])
        except ValueError:
            p = 1
        entry = entries[min(max(p - 1, 0), len(entries) - 1)]
    return entry


def _subtitle_candidates(entry: dict):
    """人工字幕优先，其次 AI 字幕；同一来源内优先含 en 的轨道。"""
    manual = entry.get("subtitles") or {}
    auto = entry.get("automatic_captions") or {}
    for source in (manual, auto):
        keys = sorted(source.keys(), key=lambda k: ("en" not in k.lower(), k))
        for key in keys:
            if key == "danmaku":  # 弹幕 XML，不是字幕
                continue
            for item in source[key] or []:
                yield key, item


def _download_subtitle(entries: list[dict], headers: dict) -> tuple[str, str, list[str]]:
    """取回 SRT 字幕，返回 (字幕文本, 轨道名, 失败原因列表)。

    B 站 extractor 的 CC/AI 字幕条目是 {'ext': 'srt', 'data': <SRT 文本>}，
    并没有 url（yt-dlp 已把字幕 JSON 转成 SRT）；优先直接用 data，
    url 只作兼容兜底，且需处理 '//' 协议相对地址。
    """
    reasons: list[str] = []
    seen_urls: set[str] = set()
    for entry in entries:
        for key, item in _subtitle_candidates(entry):
            tag = f"{key}/{item.get('ext', '')}"
            data = item.get("data")
            if isinstance(data, str) and data.strip():
                return data, key, reasons
            if data is not None:
                reasons.append(f"{tag}: data 不是有效 SRT 文本")
                continue

            url = item.get("url")
            if not url:
                reasons.append(f"{tag}: 既无 data 也无 url")
                continue
            if url.startswith("//"):
                url = "https:" + url
            if url in seen_urls:
                continue
            seen_urls.add(url)
            try:
                resp = requests.get(url, headers=headers, timeout=20)
                resp.raise_for_status()
                if item.get("ext") == "srt":
                    text = resp.text
                else:
                    payload = resp.json()
                    body = payload.get("body") or payload.get("data", {}).get("body") or []
                    text = _json_to_srt(body)
                if text.strip():
                    return text, key, reasons
                reasons.append(f"{tag}: 字幕内容为空")
            except requests.RequestException as e:
                reasons.append(f"{tag}: 下载失败 {e}")
            except (ValueError, KeyError, TypeError, AttributeError) as e:
                reasons.append(f"{tag}: 解析失败 {e}")
    return "", "", reasons


def _track_names(entries: list[dict]) -> list[str]:
    names = []
    for entry in entries:
        for field in ("subtitles", "automatic_captions"):
            names.extend(k for k in (entry.get(field) or {}) if k != "danmaku")
    return sorted(set(names))


def _login_state(cookie: str | None, headers: dict) -> str:
    """失败时用 nav 接口判断 Cookie 是否真的是登录态，便于定位原因。"""
    if not cookie:
        return "本次任务未收到 Cookie"
    try:
        data = requests.get(
            "https://api.bilibili.com/x/web-interface/nav",
            headers=headers,
            timeout=10,
        ).json()
        logged = bool((data.get("data") or {}).get("isLogin"))
        return "Cookie 已登录" if logged else "Cookie 未登录或已失效（请重新复制 SESSDATA）"
    except (requests.RequestException, ValueError) as e:
        return f"登录态检查失败：{e}"


def _ydl_info_opts(ydl_auth: dict) -> dict:
    """解析视频信息的参数：必须开启 writesubtitles，否则 yt-dlp 的
    extract_subtitles() 会直接返回空 dict，B 站字幕一个都拿不到。"""
    return {
        "quiet": True,
        "no_warnings": True,
        "noplaylist": True,
        "socket_timeout": 30,
        "writesubtitles": True,
        "writeautomaticsub": True,
        **ydl_auth,
    }


def _fmt_srt_time(t: float) -> str:
    t = max(t, 0.0)
    h = int(t // 3600)
    m = int(t % 3600 // 60)
    s = int(t % 60)
    ms = int(round((t - int(t)) * 1000)) % 1000
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _json_to_srt(body: list) -> str:
    lines = []
    for i, cue in enumerate(body, start=1):
        start = cue.get("from")
        end = cue.get("to")
        text = (cue.get("content") or "").strip()
        if start is None or end is None or not text:
            continue
        lines.append(str(i))
        lines.append(f"{_fmt_srt_time(start)} --> {_fmt_srt_time(end)}")
        lines.append(text)
        lines.append("")
    return "\n".join(lines)


def _run_job(job_id: str, url: str, cookie: str | None) -> None:
    job = _jobs[job_id]
    workdir = Path(tempfile.mkdtemp(prefix="bili-helper-"))
    job["workdir"] = str(workdir)
    headers = _job_headers(cookie)
    try:
        real_url = _resolve_short_link(url, headers)
        if not _is_bili_url(real_url):
            raise RuntimeError("只支持 B 站视频地址（bilibili.com / b23.tv）。")

        # requests 仍用带 Cookie 的请求头取字幕；yt-dlp 改用 cookiefile
        ydl_auth = _ydl_auth_opts(headers, _write_cookiefile(cookie, workdir))

        job["stage"] = "解析视频信息"
        with YoutubeDL(_ydl_info_opts(ydl_auth)) as ydl:
            info = ydl.extract_info(real_url, download=False)
        entry = _pick_part(real_url, info)
        job["title"] = entry.get("title") or job["title"]
        duration = entry.get("duration")
        job["durationSec"] = int(duration) if duration else None

        sources = [entry] if entry is info else [entry, info]
        sub_text, sub_lang, sub_reasons = _download_subtitle(sources, headers)
        if not sub_text:
            tracks = ", ".join(_track_names(sources)) or "无"
            state = _login_state(cookie, headers)
            detail = "；".join(sub_reasons[:3]) or "yt-dlp 未返回任何 CC/AI 字幕轨道"
            raise RuntimeError(
                f"没有拿到可用字幕（{state}；可用轨道：{tracks}）：{detail}。"
                "请先在 B 站网页端确认该视频确实显示 CC / AI 字幕（很多视频本身没有字幕），"
                "再确认设置里的 Cookie 含有效 SESSDATA。"
            )
        (workdir / "subtitle.srt").write_text(sub_text, encoding="utf-8")
        job["subLang"] = sub_lang
        job["progress"] = 0.08
        job["stage"] = "下载音频"

        def hook(d):
            if d.get("status") == "downloading":
                total = d.get("total_bytes") or d.get("total_bytes_estimate") or 0
                done = d.get("downloaded_bytes") or 0
                if total > 0:
                    job["progress"] = 0.08 + min(done / total, 1.0) * 0.84
            elif d.get("status") == "finished":
                job["progress"] = 0.95
                job["stage"] = "整理文件"

        ydl_opts = {
            "format": "bestaudio[ext=m4a]/bestaudio",
            "outtmpl": str(workdir / "audio.%(ext)s"),
            "quiet": True,
            "no_warnings": True,
            "noplaylist": True,
            "socket_timeout": 30,
            "progress_hooks": [hook],
            **ydl_auth,
        }
        with YoutubeDL(ydl_opts) as ydl:
            ydl.download([entry.get("webpage_url") or real_url])

        audio_files = [f for f in workdir.glob("audio.*") if f.is_file()]
        if not audio_files:
            raise RuntimeError("音频下载失败，未生成本地文件。")
        job["audioFile"] = str(audio_files[0])
        job["audioExt"] = audio_files[0].suffix.lstrip(".").lower() or "m4a"
        job["subtitleFile"] = str(workdir / "subtitle.srt")
        job["state"] = "done"
        job["progress"] = 1.0
        job["stage"] = "完成"
        job["finishedAt"] = time.time()
    except Exception as e:  # noqa: BLE001 - 任务线程内兜底，错误回传给 App
        job["state"] = "error"
        job["error"] = str(e)
        job["finishedAt"] = time.time()
        shutil.rmtree(workdir, ignore_errors=True)


def _sweep_expired() -> None:
    now = time.time()
    expired = [
        jid
        for jid, job in _jobs.items()
        if job["state"] in ("done", "error")
        and job.get("finishedAt")
        and now - job["finishedAt"] > JOB_TTL_SECONDS
    ]
    for jid in expired:
        job = _jobs.pop(jid, None)
        if job:
            d = job.get("workdir")
            if d:
                shutil.rmtree(d, ignore_errors=True)


@app.get("/api/ping")
def ping():
    return jsonify({"ok": True, "version": SERVICE_VERSION})


@app.post("/api/bili/import")
def create_import():
    body = request.get_json(silent=True) or {}
    url = (body.get("url") or "").strip()
    cookie = (body.get("cookie") or "").strip() or None
    if not url:
        return jsonify({"error": "缺少视频地址。"}), 400
    if not _is_bili_url(url):
        return jsonify({"error": "只支持 B 站视频地址（bilibili.com / b23.tv）。"}), 400

    _sweep_expired()
    job_id = uuid.uuid4().hex[:12]
    with _lock:
        _jobs[job_id] = {
            "id": job_id,
            "state": "running",
            "stage": "排队中",
            "progress": 0.0,
            "title": "",
            "durationSec": None,
            "subLang": "",
            "error": "",
            "workdir": None,
            "audioFetched": False,
            "subtitleFetched": False,
            "finishedAt": None,
            "created": time.time(),
        }
    threading.Thread(
        target=_run_job, args=(job_id, url, cookie), daemon=True
    ).start()
    return jsonify({"jobId": job_id})


def _get_job_or_404(job_id: str):
    job = _jobs.get(job_id)
    if job is None:
        return None, (jsonify({"error": "任务不存在或已过期，请重新发起导入。"}), 404)
    return job, None


@app.get("/api/bili/job/<job_id>")
def job_status(job_id: str):
    job, err = _get_job_or_404(job_id)
    if err:
        return err[1]
    return jsonify(
        {
            "jobId": job["id"],
            "state": job["state"],
            "progress": round(job["progress"], 3),
            "stage": job["stage"],
            "title": job["title"],
            "durationSec": job["durationSec"],
            "subLang": job["subLang"],
            "audioExt": job.get("audioExt") or "m4a",
            "error": job["error"],
        }
    )


def _finish_fetch(job: dict, kind: str) -> None:
    job[f"{kind}Fetched"] = True
    if job["audioFetched"] and job["subtitleFetched"]:
        shutil.rmtree(job.get("workdir") or "", ignore_errors=True)
        _jobs.pop(job["id"], None)


@app.get("/api/bili/job/<job_id>/audio")
def job_audio(job_id: str):
    job, err = _get_job_or_404(job_id)
    if err:
        return err[1]
    if job["state"] != "done":
        return jsonify({"error": "任务尚未完成。"}), 409
    path = Path(job["audioFile"])
    if not path.is_file():
        return jsonify({"error": "音频文件已失效，请重新发起导入。"}), 410
    ext = job["audioExt"]
    mime = "audio/mp4" if ext in ("m4a", "mp4") else "application/octet-stream"
    resp = send_file(path, mimetype=mime, as_attachment=True, download_name=f"audio.{ext}")
    _finish_fetch(job, "audio")
    return resp


@app.get("/api/bili/job/<job_id>/subtitle")
def job_subtitle(job_id: str):
    job, err = _get_job_or_404(job_id)
    if err:
        return err[1]
    if job["state"] != "done":
        return jsonify({"error": "任务尚未完成。"}), 409
    path = Path(job["subtitleFile"])
    if not path.is_file():
        return jsonify({"error": "字幕文件已失效，请重新发起导入。"}), 410
    resp = send_file(
        path,
        mimetype="text/plain; charset=utf-8",
        as_attachment=True,
        download_name="subtitle.srt",
    )
    _finish_fetch(job, "subtitle")
    return resp


def main() -> None:
    print("B 站配套服务已启动：http://0.0.0.0:8787（局域网内 App 可访问）")
    app.run(host="0.0.0.0", port=8787, threaded=True)


if __name__ == "__main__":
    main()
